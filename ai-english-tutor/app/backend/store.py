"""Local JSON persistence for the single-student prototype.

Audio stays under data/audio. Replace this module with a database repository when
accounts are introduced; the API routes do not need to change.
"""
from __future__ import annotations

import json
import os
import threading
from copy import deepcopy
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
AUDIO_DIR = DATA_DIR / "audio"
SESSION_DIR = DATA_DIR / "sessions"
PROGRESS_FILE = DATA_DIR / "progress.json"


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


class LocalStore:
    def __init__(self) -> None:
        AUDIO_DIR.mkdir(parents=True, exist_ok=True)
        SESSION_DIR.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()
        if not PROGRESS_FILE.exists():
            self._write_json(PROGRESS_FILE, {"learner": {"words": {}, "sessions": []}})

    @staticmethod
    def _read_json(path: Path, default):
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except (FileNotFoundError, json.JSONDecodeError):
            return deepcopy(default)

    @staticmethod
    def _write_json(path: Path, value) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_suffix(path.suffix + ".tmp")
        temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
        os.replace(temporary, path)

    def create_session(self, session: dict) -> dict:
        path = SESSION_DIR / f"{session['id']}.json"
        self._write_json(path, session)
        return session

    def get_session(self, session_id: str) -> dict | None:
        # UUIDs are generated by the server. Reject path separators regardless.
        if not session_id or any(c in session_id for c in "/\\.."):
            return None
        return self._read_json(SESSION_DIR / f"{session_id}.json", None)

    def save_session(self, session: dict) -> dict:
        session["updated_at"] = utc_now()
        self._write_json(SESSION_DIR / f"{session['id']}.json", session)
        return session

    def save_audio(self, session_id: str, filename: str, content: bytes) -> tuple[str, int]:
        safe_name = Path(filename).name
        folder = AUDIO_DIR / session_id
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / safe_name
        path.write_bytes(content)
        return f"/media/{session_id}/{safe_name}", len(content)

    def progress(self) -> dict:
        with self._lock:
            return self._read_json(PROGRESS_FILE, {"learner": {"words": {}, "sessions": []}})

    def record_word(self, word_id: str, correct: bool | None, mode: str) -> dict:
        with self._lock:
            data = self._read_json(PROGRESS_FILE, {"learner": {"words": {}, "sessions": []}})
            words = data["learner"].setdefault("words", {})
            state = words.setdefault(word_id, {
                "attempts": 0, "correct": 0, "known": False, "streak": 0, "interval_days": 0,
            })
            now = datetime.now(timezone.utc)
            state.setdefault("streak", 0)
            state.setdefault("interval_days", 0)
            state["attempts"] += 1
            if correct is True:
                state["correct"] += 1
            if correct is False:
                state["streak"] = 0
                state["interval_days"] = 0
                state["next_review"] = (now + timedelta(minutes=10)).isoformat()
            else:
                state["streak"] = state.get("streak", 0) + 1
                intervals = [1, 3, 7, 14, 30, 60]
                interval = intervals[min(state["streak"] - 1, len(intervals) - 1)]
                state["interval_days"] = interval
                state["next_review"] = (now + timedelta(days=interval)).isoformat()
            if mode == "vocabulary":
                state["known"] = bool(correct)
                if correct:
                    state["streak"] = max(state["streak"], 2)
                    state["interval_days"] = max(state["interval_days"], 7)
                    state["next_review"] = (now + timedelta(days=7)).isoformat()
            elif mode in {"dictation", "quiz", "paper"} and correct is False:
                state["known"] = False
            elif mode in {"dictation", "quiz", "paper"} and correct is True:
                accuracy = state["correct"] / max(1, state["attempts"])
                if state["streak"] >= 3 and accuracy >= 0.6:
                    state["known"] = True
            state["last_mode"] = mode
            state["last_result"] = correct
            state["last_seen"] = now.isoformat()
            self._write_json(PROGRESS_FILE, data)
            return state

    def complete_session(self, session: dict, report: dict) -> None:
        with self._lock:
            data = self._read_json(PROGRESS_FILE, {"learner": {"words": {}, "sessions": []}})
            history = data["learner"].setdefault("sessions", [])
            if not any(item["id"] == session["id"] for item in history):
                history.append({
                    "id": session["id"],
                    "topic": session["topic"],
                    "duration_seconds": session.get("elapsed_seconds", 0),
                    "turns": len(session.get("turns", [])),
                    "score": report.get("overall_score"),
                    "completed_at": utc_now(),
                })
                data["learner"]["sessions"] = history[-30:]
            self._write_json(PROGRESS_FILE, data)


store = LocalStore()
